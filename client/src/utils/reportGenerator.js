/**
 * Downloadable Safety Report Generator for CyberShield AI
 *
 * Generates and triggers download of a structured, human-readable plain text (.txt)
 * cybersecurity intelligence assessment report without introducing heavy PDF dependencies.
 */

export function generateSafetyReportText(analysisResult, options = {}) {
  if (!analysisResult) return '';

  const {
    id = 'N/A',
    message = '',
    category = 'unspecified',
    riskScore = 0,
    riskLevel = 'unknown',
    isToxic = false,
    confidence = null,
    detectedSignals = [],
    impersonationIndicators = [],
    explanation = '',
    recommendations = [],
    analyzedAt = new Date().toISOString(),
    type = 'Text Safety Analysis',
    model = 'unitary/toxic-bert'
  } = analysisResult;

  const appName = options.appName || 'CYBERSHIELD AI (Cyclops Threat Intelligence)';
  const dateFormatted = new Date(analyzedAt).toUTCString();

  const divider = '='.repeat(72);
  const subDivider = '-'.repeat(72);

  let report = `${divider}\n`;
  report += `  ${appName.toUpperCase()}\n`;
  report += `  CYBER SAFETY & ONLINE THREAT DETECTION REPORT\n`;
  report += `${divider}\n\n`;

  report += `ANALYSIS METADATA\n`;
  report += `${subDivider}\n`;
  report += `Report ID:            ${id}\n`;
  report += `Timestamp:            ${dateFormatted}\n`;
  report += `Assessment Type:      ${type}\n`;
  report += `AI Model:             ${model}\n`;
  if (confidence !== null && confidence !== undefined) {
    report += `Model Confidence:     ${Math.round(confidence <= 1 ? confidence * 100 : confidence)}%\n`;
  }
  report += `\n`;

  report += `EXECUTIVE RISK SUMMARY\n`;
  report += `${subDivider}\n`;
  report += `Risk Score:           ${riskScore} / 100\n`;
  report += `Risk Level:           ${(riskLevel || 'UNKNOWN').toUpperCase()}\n`;
  report += `Primary Category:     ${(category || 'UNKNOWN').replace(/_/g, ' ').toUpperCase()}\n`;
  report += `Toxicity Flag:        ${isToxic ? 'POSITIVE (Harmful patterns detected)' : 'NEGATIVE (Benign classification)'}\n`;
  report += `Summary Assessment:   ${explanation}\n\n`;

  if (message) {
    report += `EVALUATED CONTENT / MESSAGE\n`;
    report += `${subDivider}\n`;
    report += `"${message}"\n\n`;
  }

  if (detectedSignals && detectedSignals.length > 0) {
    report += `DETECTION SIGNALS (${detectedSignals.length} Detected)\n`;
    report += `${subDivider}\n`;
    detectedSignals.forEach((sig, index) => {
      const name = typeof sig === 'string' ? sig : sig.name;
      const desc = sig.description ? ` - ${sig.description}` : '';
      const sev = sig.severity ? ` [${sig.severity.toUpperCase()}]` : '';
      report += `  ${index + 1}. ${name}${sev}${desc}\n`;
    });
    report += `\n`;
  }

  if (impersonationIndicators && impersonationIndicators.length > 0) {
    report += `IMPERSONATION & SOCIAL ENGINEERING RISK INDICATORS\n`;
    report += `${subDivider}\n`;
    impersonationIndicators.forEach((ind, index) => {
      report += `  ${index + 1}. [${ind.category.toUpperCase()}] ${ind.pattern}\n`;
      report += `     Why Suspicious: ${ind.explanation}\n`;
      report += `     Action:         ${ind.action}\n`;
    });
    report += `\n`;
  }

  if (recommendations && recommendations.length > 0) {
    report += `RECOMMENDED SAFETY & MITIGATION ACTIONS\n`;
    report += `${subDivider}\n`;
    recommendations.forEach((rec, index) => {
      report += `  [ ] ${index + 1}. ${rec}\n`;
    });
    report += `\n`;
  }

  report += `IMPORTANT LEGAL & RESPONSIBLE AI DISCLAIMER\n`;
  report += `${subDivider}\n`;
  report += `This assessment was generated by an automated algorithmic system to assist in\n`;
  report += `evaluating online messages. AI classifications are probabilistic indicators\n`;
  report += `and should not be interpreted as definitive legal or evidentiary proof of intent.\n`;
  report += `In cases involving immediate danger, violence, or severe threats, contact\n`;
  report += `your local law enforcement authorities or emergency services immediately.\n\n`;

  report += `${divider}\n`;
  report += `End of Report — CyberShield AI / Cyclops Threat Assessment\n`;
  report += `${divider}\n`;

  return report;
}

/**
 * Initiates browser download of the generated text report
 */
export function downloadSafetyReport(analysisResult, options = {}) {
  const content = generateSafetyReportText(analysisResult, options);
  if (!content) return false;

  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');

  const filename = `CyberShield_Threat_Report_${analysisResult.id ? analysisResult.id.slice(0, 12) : Date.now()}.txt`;
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
  return true;
}

